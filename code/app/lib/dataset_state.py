# -*- coding: utf-8 -*-
"""Is the dataset still what the cartography says?  And bring it up to date.

A run never opens a shapefile. The converter (tools/gis_to_dataset.py) reads
the GIS folder once and writes GRID-INDEPENDENT tables into the dataset --
the catchment ring, the stream network, the soil zones, the vegetation
cover, the irrigation fields, the observation points, the ponds -- and those
are what a run reads. So a shapefile edited and not converted is a change the
run silently ignores.

The Grid panel ran the converter by itself, but only for the two tables a
GRID depends on; the other five were refreshed only by a button on the Soil
panel that nothing reminded anyone to press. Every table is judged here, the
Validation panel reports it, and Launch converts first when anything is out
of date.

STREAMLIT-FREE, like checks.py and runs.py.
"""

import json
import os
import subprocess
import sys

__all__ = ['GRID_TABLES', 'tables', 'provenance', 'stale', 'run_converter']

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.abspath(os.path.join(HERE, '..', '..'))
CONVERTER = os.path.join(CODE, 'tools', 'gis_to_dataset.py')

# The two tables a mesh producer reads: voronoi triangulates the ring and
# refines on the streams. The Grid panel converts before a build only when
# THESE are stale -- a vegetation edit is no reason to rebuild a grid.
GRID_TABLES = ('inputWATERSHED.csv', 'inputSTREAM.csv')


def _converter():
    """The converter as a module, for its layer list (light: it imports
    geopandas only inside its functions)."""
    import importlib.util
    name = '_mm_gis_to_dataset'
    if name in sys.modules:
        return sys.modules[name]
    for p in (CODE,):
        if p not in sys.path:
            sys.path.insert(0, p)
    spec = importlib.util.spec_from_file_location(name, CONVERTER)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def _dotted(cfg, dotted):
    obj = cfg
    for part in dotted.split('.'):
        obj = getattr(obj, part, None)
        if obj is None:
            return ''
    return str(obj or '')


def tables(cfg):
    """``[(table, shapefile, columns)]`` -- every table the converter writes
    for this configuration, the shapefile it comes from (as named in the
    configuration), and the attribute columns the configuration expects in
    it."""
    conv = _converter()
    out = [('inputWATERSHED.csv', cfg.grid.boundary, [])]
    if getattr(cfg.grid, 'streams', ''):
        out.append(('inputSTREAM.csv', cfg.grid.streams, []))
    for role, dotted, _fixed, stem in conv.VECTOR_LAYERS:
        name = _dotted(cfg, dotted)
        if name:
            cols = [c for c in conv._config_columns(cfg, role) if c]
            out.append((stem + '.geojson', name, cols))
    return out


def provenance(path):
    """What the converter recorded about a table's source: ``source``,
    ``size`` (bytes, int), ``mtime`` and ``generated`` ('YYYY-mm-dd
    HH:MM'), and for a GeoJSON
    the attribute ``columns`` its features carry. ``{}`` if unreadable."""
    try:
        if path.endswith('.geojson'):
            with open(path, encoding='utf-8') as fh:
                g = json.load(fh)
            m = dict(g.get('marmites') or {})
            feats = g.get('features') or []
            m['columns'] = sorted((feats[0].get('properties') or {})) \
                if feats else []
            return m
        out = {}
        with open(path, encoding='utf-8') as fh:
            for line in fh:
                if not line.startswith('#'):
                    break
                if line.startswith('# generated by') and ' on ' in line:
                    out['generated'] = line.rsplit(' on ', 1)[1].strip()
                    continue
                if ':' in line:
                    k, v = line[1:].split(':', 1)
                    out[k.strip()] = v.strip()
        # '# size : 5388 bytes, mtime 2014-12-26 15:40'
        size = out.get('size', '')
        if 'bytes' in size:
            out['size'] = int(size.split('bytes')[0].strip())
            if 'mtime' in size:
                out['mtime'] = size.split('mtime', 1)[1].strip()
        return out
    except (OSError, ValueError):
        return {}


def _mtime(path):
    import datetime
    return datetime.datetime.fromtimestamp(
        os.path.getmtime(path)).strftime('%Y-%m-%d %H:%M')


# the parts of a shapefile an edit can touch
_COMPANIONS = ('.dbf', '.shx', '.prj', '.cpg')


def _newer_companions(src, generated):
    """The companion files of ``src`` modified after ``generated``."""
    if not generated or not src.lower().endswith('.shp'):
        return []
    stem = src[:-4]
    out = []
    for ext in _COMPANIONS:
        f = stem + ext
        if os.path.exists(f) and _mtime(f) > generated:
            out.append(ext)
    return out


def stale(cfg, dataset_dir, gis_dir, only=None):
    """Why the dataset is out of date, one line per table (empty: it is not).

    A table is out of date when it was never written, was made from another
    file, its shapefile has changed since (size or modification time), or it
    lacks a column the configuration now names. ``only`` limits the check to
    those table names. A shapefile that is not there is left to the run's
    own checks: converting cannot fix it.
    """
    why = []
    for table, name, cols in tables(cfg):
        if only is not None and table not in only:
            continue
        out = os.path.join(str(dataset_dir), table)
        src = name if os.path.isabs(name) else os.path.join(str(gis_dir),
                                                             name)
        if not os.path.exists(out):
            if os.path.exists(src):
                why.append('%s has never been written (from %s)'
                           % (table, os.path.basename(src)))
            continue
        prov = provenance(out)
        was = prov.get('source', '')
        if was and os.path.normcase(os.path.abspath(was)) != \
                os.path.normcase(os.path.abspath(src)):
            why.append('%s was made from %s, not %s'
                       % (table, os.path.basename(was),
                          os.path.basename(src)))
            continue
        if not os.path.exists(src):
            continue
        size, mt = prov.get('size'), prov.get('mtime')
        try:
            changed = ((size not in (None, '') and
                        int(size) != os.path.getsize(src)) or
                       (mt and mt != _mtime(src)))
        except (OSError, ValueError):
            changed = False
        if changed:
            why.append('%s has changed since %s was written'
                       % (os.path.basename(src), table))
            continue
        # THE ATTRIBUTES. An edit of the table alone rewrites the .dbf and
        # leaves the .shp untouched -- recoding classes, the usual edit --
        # and the provenance records the .shp only.
        newer = _newer_companions(src, prov.get('generated', ''))
        if newer:
            why.append('%s of %s changed after %s was written'
                       % (', '.join(newer), os.path.basename(src), table))
            continue
        have = set(prov.get('columns') or [])
        lack = [c for c in cols if c not in have]
        if table.endswith('.geojson') and lack:
            why.append('%s lacks the column(s) %s the configuration names'
                       % (table, ', '.join(lack)))
    return why


def run_converter(case, cfg_path, dry=False, python_exe=None, timeout=900):
    """Run the converter as a SUBPROCESS: ``(ok, output)``.

    A subprocess keeps geopandas out of the app's import graph, and it is
    the command a user would type. ``ok`` is the exit code, not a guess from
    the text.
    """
    import mm_paths
    cmd = [python_exe or sys.executable, CONVERTER, '--case', case,
           '--config', str(cfg_path)]
    if dry:
        cmd.append('--dry-run')
    r = subprocess.run(cmd, capture_output=True, text=True,
                       cwd=str(mm_paths.REPO), timeout=timeout)
    out = (r.stdout or '') + (('\n' + r.stderr) if r.stderr else '')
    return r.returncode == 0, out
