# -*- coding: utf-8 -*-
"""GIS (Tier B) -> dataset (Tier A) converter.  WP1, step 1.1.

Run this BY HAND when the source cartography changes. It is never called by the
model, which is the whole point: geopandas and rasterio are imported here and in
the Streamlit app, and nowhere on the model path (cookbook decision D3).

    python code/tools/gis_to_dataset.py --case LaMata            # convert
    python code/tools/gis_to_dataset.py --case LaMata --dry-run  # preview only

Reads, from $MM_DATA_ROOT/GIS:
    hydrography.shp     the mapped stream network
    lm_ponds.shp        the charcas
    Limite.shp          the catchment boundary
    lm_demfill          the sink-filled DEM (native resolution)

Writes, into example/<case>/ (and nothing else):
    inputSTREAM.csv        stream geometry, GRID-INDEPENDENT: seg_id, seq, x, y
    inputSTREAM_param.csv  per-segment resolved parameters
    inputPONDS.csv         pond table: fid, centroid, area, DEM statistics
    inputWATERSHED.csv     the catchment boundary polygon

Every output carries a provenance header: which file it came from, that file's
size and mtime, its CRS, and the feature count. Re-running is idempotent apart
from the generation timestamp.

WHY THE GEOMETRY IS GRID-INDEPENDENT
------------------------------------
The cookbook's first sketch had the reach table carry cell indices. That binds
it to the 50 m structured grid, and WP1c replaces that grid with a Voronoi mesh.
So the converter emits the network in PROJECTED COORDINATES and the model maps
it onto whatever grid is current. The intermediate then survives the grid change
instead of being regenerated by it.

THE ONE PARAMETER THE CONVERTER CANNOT RESOLVE
----------------------------------------------
The `drainage` producer (w = a * A**b) needs contributing drainage area, which
is a function of the flow routing the MODEL computes on its own grid. The
converter therefore resolves `value`, `column` and `raster` and passes the
`drainage` coefficients through for the model to apply against its own flow
accumulation. D3 is still honoured in full -- no shapefile is on the model path
-- and the alternative (duplicating flow accumulation here, on a different grid
from the one the model routes on) would be worse than the problem.
"""

import argparse
import csv
import datetime
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.abspath(os.path.join(HERE, '..'))
if CODE not in sys.path:
    sys.path.insert(0, CODE)

import marmites_config as mcfg   # noqa: E402
import mm_paths                  # noqa: E402

# La Mata is ED50 / UTM zone 29N. The DEM rasters carry an equivalent but
# UNNAMED PROJCS (International 1924, central meridian -9), so a CRS comparison
# on the authority code alone would wrongly report a mismatch -- see _crs_note.
TARGET_EPSG = 23029

SOURCES = {
    'streams':   'hydrography.shp',
    'ponds':     'lm_ponds.shp',
    'watershed': 'Limite.shp',
    'dem':       'lm_demfill',
}


def _provenance(path, gdf_or_crs=None, n=None):
    st = os.stat(path)
    return [
        '# generated by code/tools/gis_to_dataset.py on %s'
        % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
        '# source   : %s' % path,
        '# size     : %d bytes, mtime %s'
        % (st.st_size, datetime.datetime.fromtimestamp(st.st_mtime)
           .strftime('%Y-%m-%d %H:%M')),
        '# crs      : %s' % (gdf_or_crs if gdf_or_crs is not None else 'n/a'),
        '# features : %s' % ('%d' % n if n is not None else 'n/a'),
    ]


def _crs_note(crs):
    """Describe a CRS, naming the unnamed-but-equivalent case explicitly."""
    if crs is None:
        return 'UNDECLARED (no .prj) -- assumed EPSG:%d' % TARGET_EPSG
    try:
        code = crs.to_epsg()
    except Exception:
        code = None
    if code:
        return 'EPSG:%d' % code
    return ('unnamed PROJCS, no EPSG code -- treated as EPSG:%d '
            '(International 1924 / UTM 29N, the ED50 definition)' % TARGET_EPSG)


def _to_target(gdf, name, report):
    import geopandas as gpd   # noqa: F401  (imported for the side effect/version)
    src = _crs_note(gdf.crs)
    if gdf.crs is None:
        gdf = gdf.set_crs(epsg=TARGET_EPSG, allow_override=True)
        report.append('%-12s CRS undeclared -> assumed EPSG:%d' % (name, TARGET_EPSG))
    else:
        code = None
        try:
            code = gdf.crs.to_epsg()
        except Exception:
            pass
        if code and code != TARGET_EPSG:
            gdf = gdf.to_crs(epsg=TARGET_EPSG)
            report.append('%-12s reprojected EPSG:%d -> EPSG:%d'
                          % (name, code, TARGET_EPSG))
        else:
            report.append('%-12s %s (no reprojection)' % (name, src))
    return gdf


def _write_csv(path, header_lines, columns, rows, dry_run=False):
    if dry_run:
        print('   would write %-24s %d row(s)' % (os.path.basename(path), len(rows)))
        return path
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        for line in header_lines:
            fh.write(line + '\n')
        w = csv.writer(fh)
        w.writerow(columns)
        w.writerows(rows)
    print('   wrote %-26s %d row(s)' % (os.path.basename(path), len(rows)))
    return path


def convert(case='LaMata', gis=None, out_dir=None, cfg=None, dry_run=False):
    import geopandas as gpd
    import numpy as np
    import rasterio


    gis = gis or str(mm_paths.GIS)
    out_dir = out_dir or str(mm_paths.dataset_dir(case))
    cfg = cfg or mcfg.RunConfig.from_dict({})
    if not os.path.isdir(gis):
        raise SystemExit('GIS source folder not found: %s\n'
                         'Set MM_DATA_ROOT or pass --gis.' % gis)
    if not os.path.isdir(out_dir):
        raise SystemExit('case folder not found: %s' % out_dir)

    print('GIS -> dataset')
    print('   source : %s' % gis)
    print('   target : %s' % out_dir)
    report = []
    written = []

    # ---------------------------------------------------------------- streams
    p = os.path.join(gis, SOURCES['streams'])
    streams = _to_target(gpd.read_file(p), 'streams', report)
    vert_rows, par_rows = [], []
    w_src, m_src = cfg.sfr.width, cfg.sfr.manning
    for seg_id, (_, row) in enumerate(streams.iterrows()):
        geom = row.geometry
        parts = (list(geom.geoms) if geom.geom_type.startswith('Multi') else [geom])
        for part in parts:
            for seq, (x, y) in enumerate(part.coords):
                vert_rows.append([seg_id, seq, '%.3f' % x, '%.3f' % y])
        par_rows.append([
            seg_id,
            int(row.get('GRID_CODE', 0) or 0),
            '%.2f' % geom.length,
            _resolve(w_src, row, 'width'),
            _resolve(m_src, row, 'manning'),
            _resolve(cfg.sfr.rhk, row, 'rhk'),
            _resolve(cfg.sfr.rbth, row, 'rbth'),
        ])
    hdr = _provenance(p, _crs_note(streams.crs), len(streams))
    written.append(_write_csv(
        os.path.join(out_dir, 'inputSTREAM.csv'),
        hdr + ['# stream geometry in EPSG:%d -- GRID-INDEPENDENT, the model maps'
               ' it onto its own grid' % TARGET_EPSG],
        ['seg_id', 'seq', 'x', 'y'], vert_rows, dry_run))
    written.append(_write_csv(
        os.path.join(out_dir, 'inputSTREAM_param.csv'),
        hdr + ['# per-segment parameters resolved from the [sfr] producers.',
               '# "drainage:a=..,b=.." means the MODEL computes w = a*A**b from its',
               '# own flow accumulation -- see the module docstring.'],
        ['seg_id', 'grid_code', 'length_m', 'width_m', 'manning', 'rhk', 'rbth'],
        par_rows, dry_run))

    # ------------------------------------------------------------------ ponds
    p = os.path.join(gis, SOURCES['ponds'])
    ponds = _to_target(gpd.read_file(p), 'ponds', report)
    dem_path = os.path.join(gis, SOURCES['dem'])
    pond_rows = []
    have_dem = os.path.exists(dem_path)
    if not have_dem:
        report.append('%-12s %s not found -- DEM columns left blank'
                      % ('dem', SOURCES['dem']))
    for _, row in ponds.iterrows():
        g = row.geometry
        c = g.centroid
        dmean = dmin = ''
        if have_dem:
            try:
                v = _sample_polygon(dem_path, g)
                if v.size:
                    dmean, dmin = '%.2f' % v.mean(), '%.2f' % v.min()
            except Exception as exc:                     # pragma: no cover
                report.append('%-12s DEM sampling failed for pond %s: %s'
                              % ('dem', row.get('id', '?'), exc))
        pond_rows.append([int(row.get('id', 0) or 0), '%.3f' % c.x, '%.3f' % c.y,
                          '%.1f' % g.area, '%.1f' % g.length, dmean, dmin])
    written.append(_write_csv(
        os.path.join(out_dir, 'inputPONDS.csv'),
        _provenance(p, _crs_note(ponds.crs), len(ponds))
        + ['# dem_mean_m / dem_min_m sampled from %s over each footprint;'
           % SOURCES['dem'],
           '# the model sets rim = dem_mean and bottom = rim - pond depth.'],
        ['fid', 'x', 'y', 'area_m2', 'perimeter_m', 'dem_mean_m', 'dem_min_m'],
        pond_rows, dry_run))

    # -------------------------------------------------------------- watershed
    p = os.path.join(gis, SOURCES['watershed'])
    ws = _to_target(gpd.read_file(p), 'watershed', report)
    ws_rows = []
    for ring_id, (_, row) in enumerate(ws.iterrows()):
        g = row.geometry
        polys = (list(g.geoms) if g.geom_type.startswith('Multi') else [g])
        for poly in polys:
            for seq, (x, y) in enumerate(poly.exterior.coords):
                ws_rows.append([ring_id, seq, '%.3f' % x, '%.3f' % y])
    written.append(_write_csv(
        os.path.join(out_dir, 'inputWATERSHED.csv'),
        _provenance(p, _crs_note(ws.crs), len(ws))
        + ['# catchment boundary in EPSG:%d -- the Voronoi domain (WP1c).'
           % TARGET_EPSG],
        ['ring_id', 'seq', 'x', 'y'], ws_rows, dry_run))

    print('\nCRS handling:')
    for line in report:
        print('   %s' % line)
    if dry_run:
        print('\n--dry-run: nothing was written.')
    return written


def _sample_polygon(raster_path, geom):
    """Raster values whose cell CENTRES fall inside ``geom``.

    Deliberately does NOT use rasterio.mask / windows.from_bounds: on this
    environment that path reaches numpy.linalg.solve through
    rasterio.transform.rowcol and dies with a native delay-load DLL failure
    (0xc06d007f) -- the same class of crash as the plotting tests. Inverting the
    affine transform is closed-form and needs no LAPACK, so we do it by hand.
    """
    import numpy as np
    import rasterio
    from shapely.geometry import Point

    with rasterio.open(raster_path) as r:
        T = r.transform
        inv = ~T                        # affine.Affine inverse: pure Python
        minx, miny, maxx, maxy = geom.bounds
        cols, rows_ = [], []
        for x, y in ((minx, maxy), (maxx, miny), (minx, miny), (maxx, maxy)):
            c, rr = inv * (x, y)
            cols.append(c)
            rows_.append(rr)
        c0 = max(0, int(np.floor(min(cols))) - 1)
        c1 = min(r.width, int(np.ceil(max(cols))) + 1)
        r0 = max(0, int(np.floor(min(rows_))) - 1)
        r1 = min(r.height, int(np.ceil(max(rows_))) + 1)
        if c1 <= c0 or r1 <= r0:
            return np.array([])
        arr = r.read(1, window=((r0, r1), (c0, c1))).astype('float64')
        nodata = r.nodata

    out = []
    for i in range(arr.shape[0]):
        for j in range(arr.shape[1]):
            v = arr[i, j]
            if not np.isfinite(v) or v <= -1e30:
                continue
            if nodata is not None and v == nodata:
                continue
            x, y = T * (c0 + j + 0.5, r0 + i + 0.5)
            if geom.contains(Point(x, y)):
                out.append(v)
    return np.array(out, dtype='float64')


def _resolve(src, row, what):
    """Resolve one ParamSource against a shapefile row."""
    prod = src.producer()
    if prod == 'value':
        return '%.6g' % src.value
    if prod == 'column':
        if src.column not in row.index:
            raise SystemExit(
                'sfr.%s asks for column %r but the stream shapefile has: %s'
                % (what, src.column, [c for c in row.index if c != 'geometry']))
        return '%.6g' % float(row[src.column])
    if prod == 'raster':
        raise SystemExit('sfr.%s: the raster producer is not implemented yet '
                         '(no La Mata source needs it)' % what)
    if prod == 'drainage':
        return 'drainage:a=%g,b=%g' % (src.drainage['a'], src.drainage['b'])
    raise SystemExit('sfr.%s has no producer set' % what)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--case', default='LaMata')
    ap.add_argument('--gis', default=None, help='override $MM_DATA_ROOT/GIS')
    ap.add_argument('--out', default=None, help='override example/<case>/')
    ap.add_argument('--config', default=None,
                    help='run configuration whose [sfr] producers are used '
                         '(default: the schema defaults)')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    cfg = mcfg.load_run_config(a.config) if a.config else None
    convert(case=a.case, gis=a.gis, out_dir=a.out, cfg=cfg, dry_run=a.dry_run)
    return 0


if __name__ == '__main__':
    sys.exit(main())
