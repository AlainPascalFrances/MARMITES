# La Mata is ED50 / UTM zone 29N. The DEM rasters carry an equivalent but
# UNNAMED PROJCS (International 1924, central meridian -9), so a CRS comparison
# on the authority code alone would wrongly report a mismatch -- see _crs_note.
TARGET_EPSG = 23029

# WP1d: `streams` and `ponds` are NOT here any more -- they are named in
# [grid], which is where panel 1 asks for them, and a catchment that has
# neither is a legitimate thing to convert. Only the DEM and the pre-WP1d
# watershed fallback keep a hardcoded name.
SOURCES = {
    # The catchment now comes from [grid] boundary; this is only the fallback
    # for a configuration that does not name one. Limite.shp, which WP1 used,
    # is 19.159 km2 against the catchment's 4.844 km2 -- nearly four times too
    # big, and the reason the mesh producer had to clip to the grid rectangle.
    'watershed': 'lm_lim.shp',
}

# WP1d: the layers the four panels wrap onto the grid. Each entry says where
# the source name comes from in the configuration, which attribute columns to
# carry, and what the derived file is called. Geometry is exported in MODEL
# CRS and stays GRID-INDEPENDENT -- the wrapping happens at run time, against
# whichever grid panel 1 produced.
VECTOR_LAYERS = [
    ('boundary',  'grid.boundary',           [],                'inputBOUNDARY'),
    ('soil',      'soil.zones.layer',        ['SoilType', 'SoilCode', 'SOILthick',
                                              'ibound_l1', 'ibound_l2', 'iuzfbnd'],
     'inputSOILZONES'),
    ('vegetation', 'soil.veg_layer',         ['Species'],       'inputVEG'),
    ('irrigation', 'surface.irr_zones.layer', ['field_id'],       'inputIRR'),
    ('obs',       'obs.layer',               ['Name', 'lay', 'hi', 'h0', 'RC',
                                              'STO', 'NameReal', 'onMap'],
     'inputOBSPTS'),
    # [grid] ponds, not [lak] polygons: ONE place names the file, and it is
    # the panel that asks for it first. The LAK builder needs these polygons
    # -- it fits an embedded lake to each footprint, which the centroid table
    # inputPONDS.csv cannot give it -- and reads the GeoJSON written here.
    ('ponds',     'grid.ponds',              ['id'],            'inputPONDS'),
]


def _dotted(obj, dotted):
    for part in dotted.split('.'):
        obj = getattr(obj, part, None)
        if obj is None:
            return None
    return obj


def _export_vector(gis, out_dir, cfg, report, dry_run=False):
    """Export the configured vector layers as derived GeoJSON (WP1 tier A).

    Two tiers, as WP1 established them and the modeller confirmed (C.7): the
    shapefiles stay in ``DATA_ROOT/GIS`` and only this converter reads them;
    what a run reads is the derived file, in model CRS, carrying the geometry
    and ONLY the columns the configuration asked for. The dataset therefore
    stays self-contained without the repository ever holding a shapefile.

    Coordinates are rounded to the centimetre. On La Mata that costs 0.031
    percentage points on the worst vegetation cell -- far below the mapping
    behind it -- and roughly halves the file.
    """
    import geopandas as gpd

    import marmites_vector as mv

    written = []
    for role, dotted, columns, stem in VECTOR_LAYERS:
        name = _dotted(cfg, dotted)
        if not name:
            report.append('%-12s not configured (%s) -- skipped' % (role, dotted))
            continue
        src = os.path.join(gis, name)
        if not os.path.exists(src):
            report.append('%-12s %s NOT FOUND in %s' % (role, name, gis))
            continue
        gdf = _to_target(gpd.read_file(src), role, report)
        have = [c for c in columns if c in gdf.columns]
        missing = [c for c in columns if c not in gdf.columns]
        kind = ('point' if gdf.geom_type.iloc[0].endswith('Point')
                else 'line' if 'Line' in gdf.geom_type.iloc[0] else 'polygon')
        geoms, props = [], []
        for _, row in gdf.iterrows():
            g = row.geometry
            if g is None or g.is_empty:
                continue
            if kind == 'point':
                geoms.append((g.x, g.y))
            elif kind == 'line':
                parts = (list(g.geoms) if g.geom_type.startswith('Multi') else [g])
                geoms.append([list(part.coords) for part in parts])
            else:
                polys = (list(g.geoms) if g.geom_type.startswith('Multi') else [g])
                rings = []
                for poly in polys:
                    rings.append(list(poly.exterior.coords))
                    rings.extend(list(r.coords) for r in poly.interiors)
                geoms.append(rings)
            props.append({c: _plain(row[c]) for c in have})
        out = os.path.join(out_dir, stem + '.geojson')
        if dry_run:
            print('   would write %-24s %d feature(s)'
                  % (os.path.basename(out), len(geoms)))
        else:
            mv.write_geojson(out, kind, geoms, props,
                             crs=_crs_note(gdf.crs),
                             provenance=_provenance_dict(src, len(geoms)))
            print('   wrote %-26s %d feature(s), %.1f KB'
                  % (os.path.basename(out), len(geoms),
                     os.path.getsize(out) / 1024.0))
        written.append(out)
        if missing:
            report.append('%-12s columns not in the layer: %s (it has: %s)'
                          % (role, ', '.join(missing),
                             ', '.join(c for c in gdf.columns if c != 'geometry')))
    return written


def _plain(v):
    """A JSON-safe scalar: numpy types and NaT/NaN do not survive json.dump."""
    try:
        import numpy as np
        if isinstance(v, np.generic):
            v = v.item()
    except Exception:                                        # pragma: no cover
        pass
    if v is None or (isinstance(v, float) and v != v):
        return None
    return v if isinstance(v, (int, float, bool, str)) else str(v)


def _provenance_dict(path, n):
    st = os.stat(path)
    return {
        'generated': datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
        'generator': 'code/tools/gis_to_dataset.py',
        'source': path,
        'size': st.st_size,
        'mtime': datetime.datetime.fromtimestamp(st.st_mtime)
                 .strftime('%Y-%m-%d %H:%M'),
        'features': n,
    }


def _provenance(path, gdf_or_crs=None, n=None):
    st = os.stat(path)
    return [
        '# generated by code/tools/gis_to_dataset.py on %s'
        % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
        '# source   : %s' % path,
        '# size     : %d bytes, mtime %s'
        % (st.st_size, datetime.datetime.fromtimestamp(st.st_mtime)
           .strftime('%Y-%m-%d %H:%M')),
        '# crs      : %s' % (gdf_or_crs if gdf_or_crs is not None else 'n/a'),
        '# features : %s' % ('%d' % n if n is not None else 'n/a'),
    ]


def _crs_note(crs):
    """Describe a CRS, naming the unnamed-but-equivalent case explicitly."""
    if crs is None:
        return 'UNDECLARED (no .prj) -- assumed EPSG:%d' % TARGET_EPSG
    try:
        code = crs.to_epsg()
    except Exception:
        code = None
    if code:
        return 'EPSG:%d' % code
    return ('unnamed PROJCS, no EPSG code -- treated as EPSG:%d '
            '(International 1924 / UTM 29N, the ED50 definition)' % TARGET_EPSG)


def _to_target(gdf, name, report):
    import geopandas as gpd   # noqa: F401  (imported for the side effect/version)
    src = _crs_note(gdf.crs)
    if gdf.crs is None:
        gdf = gdf.set_crs(epsg=TARGET_EPSG, allow_override=True)
        report.append('%-12s CRS undeclared -> assumed EPSG:%d' % (name, TARGET_EPSG))
    else:
        code = None
        try:
            code = gdf.crs.to_epsg()
        except Exception:
            pass
        if code and code != TARGET_EPSG:
            gdf = gdf.to_crs(epsg=TARGET_EPSG)
            report.append('%-12s reprojected EPSG:%d -> EPSG:%d'
                          % (name, code, TARGET_EPSG))
        else:
            report.append('%-12s %s (no reprojection)' % (name, src))
    return gdf


def _write_csv(path, header_lines, columns, rows, dry_run=False):
    if dry_run:
        print('   would write %-24s %d row(s)' % (os.path.basename(path), len(rows)))
        return path
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        for line in header_lines:
            fh.write(line + '\n')
        w = csv.writer(fh)
        w.writerow(columns)
        w.writerows(rows)
    print('   wrote %-26s %d row(s)' % (os.path.basename(path), len(rows)))
    return path


def convert(case='LaMata', gis=None, out_dir=None, cfg=None, dry_run=False,
            redo_elevation=False):
    import geopandas as gpd
    import numpy as np
    import rasterio


    gis = gis or str(mm_paths.GIS)
    out_dir = out_dir or str(mm_paths.dataset_dir(case))
    cfg = cfg or mcfg.RunConfig.from_dict({})
    if not os.path.isdir(gis):
        raise SystemExit('GIS source folder not found: %s\n'
                         'Set MM_DATA_ROOT or pass --gis.' % gis)
    if not os.path.isdir(out_dir):
        raise SystemExit('case folder not found: %s' % out_dir)

    print('GIS -> dataset')
    print('   source : %s' % gis)
    print('   target : %s' % out_dir)
    report = []
    written = []

    # ---------------------------------------------------------------- streams
    # Absent is a valid answer: panel 1 asks for the layer and leaves it
    # blank until there is one, and the refinement that needs it cannot be
    # switched on meanwhile (RunConfig.validate).
    name = cfg.grid.streams
    p = os.path.join(gis, name) if name else ''
    if not name:
        report.append('%-12s not set in [grid] -- inputSTREAM*.csv not '
                      'written' % 'streams')
    elif not os.path.exists(p):
        raise SystemExit('CONFIG ERROR: grid.streams = %r is not in %s'
                         % (name, gis))
    streams = (_to_target(gpd.read_file(p), 'streams', report)
               if name else None)
    vert_rows, par_rows = [], []
    w_src, m_src = cfg.sfr.width, cfg.sfr.manning
    for seg_id, (_, row) in enumerate(
            streams.iterrows() if streams is not None else []):
        geom = row.geometry
        parts = (list(geom.geoms) if geom.geom_type.startswith('Multi') else [geom])
        for part in parts:
            for seq, (x, y) in enumerate(part.coords):
                vert_rows.append([seg_id, seq, '%.3f' % x, '%.3f' % y])
        par_rows.append([
            seg_id,
            int(row.get('GRID_CODE', 0) or 0),
            '%.2f' % geom.length,
            _resolve(w_src, row, 'width'),
            _resolve(m_src, row, 'manning'),
            _resolve(cfg.sfr.rhk, row, 'rhk'),
            _resolve(cfg.sfr.rbth, row, 'rbth'),
        ])
    if streams is not None:
        written.extend(_write_stream_tables(
            out_dir, _provenance(p, _crs_note(streams.crs), len(streams)),
            vert_rows, par_rows, dry_run))

    # ------------------------------------------------------------------ ponds
    name = cfg.grid.ponds
    p = os.path.join(gis, name) if name else ''
    if not name:
        report.append('%-12s not set in [grid] -- inputPONDS.csv not written'
                      % 'ponds')
    elif not os.path.exists(p):
        raise SystemExit('CONFIG ERROR: grid.ponds = %r is not in %s'
                         % (name, gis))
    ponds = _to_target(gpd.read_file(p), 'ponds', report) if name else None
    dem_path = os.path.join(gis, cfg.grid.dem) if cfg.grid.dem else ''
    pond_rows = []
    have_dem = bool(dem_path) and os.path.exists(dem_path)
    if not cfg.grid.dem:
        report.append('%-12s not set in [grid] -- pond rim and bottom left '
                      'blank' % 'dem')
    elif not have_dem:
        report.append('%-12s %s NOT FOUND in %s -- DEM columns left blank'
                      % ('dem', cfg.grid.dem, gis))
    for _, row in (ponds.iterrows() if ponds is not None else []):
        g = row.geometry
        c = g.centroid
        dmean = dmin = ''
        if have_dem:
            try:
                v = _sample_polygon(dem_path, g)
                if v.size:
                    dmean, dmin = '%.2f' % v.mean(), '%.2f' % v.min()
            except Exception as exc:                     # pragma: no cover
                report.append('%-12s DEM sampling failed for pond %s: %s'
                              % ('dem', row.get('id', '?'), exc))
        pond_rows.append([int(row.get('id', 0) or 0), '%.3f' % c.x, '%.3f' % c.y,
                          '%.1f' % g.area, '%.1f' % g.length, dmean, dmin])
    if ponds is not None:
        written.append(_write_csv(
            os.path.join(out_dir, 'inputPONDS.csv'),
            _provenance(p, _crs_note(ponds.crs), len(ponds))
            + ['# dem_mean_m / dem_min_m sampled from %s over each footprint;'
               % (cfg.grid.dem or 'no DEM'),
               '# the model sets rim = dem_mean and bottom = rim - pond '
               'depth.'],
            ['fid', 'x', 'y', 'area_m2', 'perimeter_m', 'dem_mean_m',
             'dem_min_m'],
            pond_rows, dry_run))

    # -------------------------------------------------------------- watershed
    p = os.path.join(gis, cfg.grid.boundary or SOURCES['watershed'])
    ws = _to_target(gpd.read_file(p), 'watershed', report)
    ws_rows = []
    for ring_id, (_, row) in enumerate(ws.iterrows()):
        g = row.geometry
        polys = (list(g.geoms) if g.geom_type.startswith('Multi') else [g])
        for poly in polys:
            for seq, (x, y) in enumerate(poly.exterior.coords):
                ws_rows.append([ring_id, seq, '%.3f' % x, '%.3f' % y])
    written.append(_write_csv(
        os.path.join(out_dir, 'inputWATERSHED.csv'),
        _provenance(p, _crs_note(ws.crs), len(ws))
        + ['# catchment boundary in EPSG:%d -- the Voronoi domain (WP1c).'
           % TARGET_EPSG],
        ['ring_id', 'seq', 'x', 'y'], ws_rows, dry_run))

    # ------------------------------------------------------------ elevation
    written.extend(_derive_elevation(gis, out_dir, cfg,
                                     tuple(ws.total_bounds), report, dry_run,
                                     redo=redo_elevation))

    # ------------------------------------------------- WP1d: vector layers
    written += _export_vector(gis, out_dir, cfg, report, dry_run)

    print('\nCRS handling:')
    for line in report:
        print('   %s' % line)
    if dry_run:
        print('\n--dry-run: nothing was written.')
    return written


def _sample_polygon(raster_path, geom):
    """Raster values whose cell CENTRES fall inside ``geom``.

    Does not use rasterio.mask / windows.from_bounds. Inverting a 2-D affine
    transform is closed-form, so doing it by hand is cheaper than the mask
    machinery and drops a LAPACK call from a purely geometric step.

    (Historical note: this was first written to dodge a native 0xc06d007f crash
    in rasterio.transform.rowcol. That crash was NOT a rasterio or LAPACK fault
    -- it was this env's Library\bin missing from PATH because python.exe had
    been launched without activation, which breaks every delay-loaded MKL DLL.
    Run activated and rasterio.mask works fine. The hand inverse is kept on its
    own merits, not as a workaround.)
    """
    import numpy as np
    import rasterio
    from shapely.geometry import Point

    with rasterio.open(raster_path) as r:
        T = r.transform
        inv = ~T                        # affine.Affine inverse: pure Python
        minx, miny, maxx, maxy = geom.bounds
        cols, rows_ = [], []
        for x, y in ((minx, maxy), (maxx, miny), (minx, miny), (maxx, maxy)):
            c, rr = inv * (x, y)
            cols.append(c)
            rows_.append(rr)
        c0 = max(0, int(np.floor(min(cols))) - 1)
        c1 = min(r.width, int(np.ceil(max(cols))) + 1)
        r0 = max(0, int(np.floor(min(rows_))) - 1)
        r1 = min(r.height, int(np.ceil(max(rows_))) + 1)
        if c1 <= c0 or r1 <= r0:
            return np.array([])
        arr = r.read(1, window=((r0, r1), (c0, c1))).astype('float64')
        nodata = r.nodata

    out = []
    for i in range(arr.shape[0]):
        for j in range(arr.shape[1]):
            v = arr[i, j]
            if not np.isfinite(v) or v <= -1e30:
                continue
            if nodata is not None and v == nodata:
                continue
            x, y = T * (c0 + j + 0.5, r0 + i + 0.5)
            if geom.contains(Point(x, y)):
                out.append(v)
    return np.array(out, dtype='float64')


def _write_stream_tables(out_dir, hdr, vert_rows, par_rows, dry_run):
    """The two stream tables. A function because they are now CONDITIONAL:
    a catchment with no mapped network writes neither."""
    return [
        _write_csv(
            os.path.join(out_dir, 'inputSTREAM.csv'),
            hdr + ['# stream geometry in EPSG:%d -- GRID-INDEPENDENT, the '
                   'model maps it onto its own grid' % TARGET_EPSG],
            ['seg_id', 'seq', 'x', 'y'], vert_rows, dry_run),
        _write_csv(
            os.path.join(out_dir, 'inputSTREAM_param.csv'),
            hdr + ['# per-segment parameters resolved from the [sfr] '
                   'producers.',
                   '# A "drainage:" width is resolved by the MODEL, on the '
                   'routed',
                   '# network, in one of two laws:',
                   '#   w_min,w_max,power  arbolate-sum scaling, w = w_min +',
                   '#                      (w_max-w_min)*(arb/arb_max)**power',
                   '#   a,b                a Hack-type law, w = a*A**b, with '
                   'the',
                   '#                      catchment area A in km2',
                   '# -- see the module docstring.'],
            ['seg_id', 'grid_code', 'length_m', 'width_m', 'manning', 'rhk',
             'rbth'], par_rows, dry_run),
    ]



