# -*- coding: utf-8 -*-
"""GIS (Tier B) -> dataset (Tier A) converter.  WP1, step 1.1.

Run this BY HAND when the source cartography changes. It is never called by the
model, which is the whole point: geopandas and rasterio are imported here and in
the Streamlit app, and nowhere on the model path (cookbook decision D3).

    python code/tools/gis_to_dataset.py --case LaMata            # convert
    python code/tools/gis_to_dataset.py --case LaMata --dry-run  # preview only

Reads, from $MM_DATA_ROOT/GIS, whatever the CONFIGURATION names -- nothing
here is hardcoded any more except the DEM, because a new catchment starts
with an empty list and panel 1 is where the layers are given:
    [grid] boundary     the catchment polygon          (required)
    [grid] streams      the mapped stream network      (optional)
    [grid] ponds        the charcas                    (optional)
    [grid] dem          the sink-filled DEM            (optional)

An optional layer left blank is simply not converted, and the refinement
that would need it cannot be switched on (RunConfig.validate).

Writes, into example/<case>/ (and nothing else):
    inputSTREAM.csv        stream geometry, GRID-INDEPENDENT: seg_id, seq, x, y
    inputSTREAM_param.csv  per-segment resolved parameters
    inputPONDS.csv         pond table: fid, centroid, area, DEM statistics
    inputWATERSHED.csv     the catchment boundary polygon
    inputDEM.asc           the land surface at the DEM's OWN resolution,
                           clipped to the catchment. Wrapped onto the model
                           cells at run time, whatever the grid kind --
                           resampling it here would throw away what the
                           survey knows before the mesh ever sees it.

Every output carries a provenance header: which file it came from, that file's
size and mtime, its CRS, and the feature count. Re-running is idempotent apart
from the generation timestamp.

WHY THE GEOMETRY IS GRID-INDEPENDENT
------------------------------------
The cookbook's first sketch had the reach table carry cell indices. That binds
it to the 50 m structured grid, and WP1c replaces that grid with a Voronoi mesh.
So the converter emits the network in PROJECTED COORDINATES and the model maps
it onto whatever grid is current. The intermediate then survives the grid change
instead of being regenerated by it.

THE ONE PARAMETER THE CONVERTER CANNOT RESOLVE
----------------------------------------------
The `drainage` producer (w = a * A**b) needs contributing drainage area, which
is a function of the flow routing the MODEL computes on its own grid. The
converter therefore resolves `value`, `column` and `raster` and passes the
`drainage` coefficients through for the model to apply against its own flow
accumulation. D3 is still honoured in full -- no shapefile is on the model path
-- and the alternative (duplicating flow accumulation here, on a different grid
from the one the model routes on) would be worse than the problem.
"""

