def _stamp(t=None):
    return (datetime.datetime.fromtimestamp(t) if t is not None
            else datetime.datetime.now()).strftime('%Y-%m-%d %H:%M')


def _cfg():
    import marmites_config as mcfg
    cfg = mcfg.RunConfig.from_dict({})
    cfg.grid.boundary = 'ring.shp'
    cfg.grid.streams = ''
    cfg.soil.veg_layer = 'veg.shp'
    cfg.soil.veg_column = 'Species'
    return cfg


def _shp(gis, name, size=100):
    stem = os.path.join(gis, name[:-4])
    for ext in ('.shp', '.shx', '.dbf'):
        with open(stem + ext, 'wb') as fh:
            fh.write(b'x' * size)
    return stem + '.shp'


def _geojson(ds, table, src, columns=('Species',), generated=None):
    st = os.stat(src)
    prov = {'source': src, 'size': st.st_size, 'mtime': _stamp(st.st_mtime),
            'generated': generated or _stamp()}
    feats = [{'type': 'Feature', 'geometry': None,
              'properties': {c: 'g' for c in columns}}]
    with open(os.path.join(ds, table), 'w', encoding='utf-8') as fh:
        json.dump({'type': 'FeatureCollection', 'marmites': prov,
                   'features': feats}, fh)


def _csv(ds, table, src):
    st = os.stat(src)
    with open(os.path.join(ds, table), 'w', encoding='utf-8') as fh:
        fh.write('# generated by code/tools/gis_to_dataset.py on %s\n'
                 % _stamp())
        fh.write('# source   : %s\n' % src)
        fh.write('# size     : %d bytes, mtime %s\n'
                 % (st.st_size, _stamp(st.st_mtime)))
        fh.write('ring_id,seq,x,y\n')


@pytest.fixture
def world(tmp_path):
    gis, ds = tmp_path / 'GIS', tmp_path / 'ds'
    gis.mkdir()
    ds.mkdir()
    ring = _shp(str(gis), 'ring.shp')
    veg = _shp(str(gis), 'veg.shp')
    _csv(str(ds), 'inputWATERSHED.csv', ring)
    _geojson(str(ds), 'inputBOUNDARY.geojson', ring, columns=())
    _geojson(str(ds), 'inputVEG.geojson', veg)
    return _cfg(), str(ds), str(gis), veg


def _grow(path):
    with open(path, 'ab') as fh:
        fh.write(b'more')


def test_a_dataset_just_converted_is_fresh(world):
    cfg, ds, gis, _veg = world
    assert dst.stale(cfg, ds, gis) == []


def test_an_edited_shapefile_makes_its_table_stale(world):
    cfg, ds, gis, veg = world
    _grow(veg)
    assert dst.stale(cfg, ds, gis) == [
        'veg.shp has changed since inputVEG.geojson was written']


def test_an_attribute_edit_alone_is_caught_by_the_dbf(world):
    """Recoding classes rewrites the .dbf and leaves the .shp untouched."""
    cfg, ds, gis, veg = world
    _geojson(ds, 'inputVEG.geojson', veg, generated='2000-01-01 00:00')
    why = dst.stale(cfg, ds, gis)
    assert len(why) == 1 and '.dbf' in why[0] and 'inputVEG' in why[0]


def test_a_column_the_configuration_now_names_makes_it_stale(world):
    cfg, ds, gis, _veg = world
    cfg.soil.veg_column = 'Class'
    why = dst.stale(cfg, ds, gis)
    assert why and 'lacks the column(s) Class' in why[0]


def test_a_table_never_written_is_stale_a_missing_shapefile_is_not(world):
    cfg, ds, gis, veg = world
    os.remove(os.path.join(ds, 'inputVEG.geojson'))
    assert dst.stale(cfg, ds, gis) == [
        'inputVEG.geojson has never been written (from veg.shp)']
    for ext in ('.shp', '.shx', '.dbf'):
        os.remove(veg[:-4] + ext)
    assert dst.stale(cfg, ds, gis) == [], \
        'converting cannot conjure a shapefile: the run reports that'


def test_only_limits_the_check_to_the_grid_tables(world):
    cfg, ds, gis, veg = world
    _grow(veg)
    assert dst.stale(cfg, ds, gis, only=dst.GRID_TABLES) == []


def test_the_validation_panel_reports_it_without_blocking_launch(
        world, monkeypatch):
    cfg, ds, gis, veg = world
    _grow(veg)
    spec = importlib.util.spec_from_file_location(
        '_mm_checks_ds', os.path.join(CODE, 'app', 'lib', 'checks.py'))
    chk = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(chk)
    import mm_paths
    monkeypatch.setattr(mm_paths, 'GIS', gis)
    got = list(chk.check_dataset_fresh(cfg, dataset_dir=ds))
    assert [c.level for c in got] == [chk.INFO], 'must not block Launch'
    assert 'Launch converts them first' in got[0].title
    assert 'veg.shp' in got[0].detail
    assert chk.check_dataset_fresh in chk.CHECKS


def test_the_real_tables_cover_every_layer_the_converter_writes():
    import marmites_config as mcfg
    cfg = mcfg.load_run_config(os.path.join(CODE, 'configs', 'lamata.toml'))
    names = [t for t, _s, _c in dst.tables(cfg)]
    for t in ('inputWATERSHED.csv', 'inputVEG.geojson',
              'inputSOILZONES.geojson', 'inputOBSPTS.geojson'):
        assert t in names, t
